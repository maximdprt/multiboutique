-- Mise à jour du stock sans risque de doublon si deux commandes arrivent en même temps.
create or replace function adjust_stock(p_id text, p_delta int)
returns void language sql as $$
  update products set stock = greatest(0, stock + p_delta), updated_at = now()
  where id = p_id and stock is not null;
$$;

