-- 001 : tables de base (boutiques, produits, guides, commandes).
-- Toutes les boutiques partagent les mêmes tables : chaque ligne porte l'identifiant de sa boutique (site_id).
-- Comme les suivantes, cette migration peut être rejouée sans risque sur une base existante.

create table if not exists sites (
  id               text primary key,
  name             text not null,
  domain           text not null unique,
  tagline          text not null default '',
  description      text not null default '',
  hero_title       text not null default '',
  hero_text        text not null default '',
  hero_product_id  text,
  theme            jsonb not null default '{}',
  legal            jsonb not null default '{}',
  shipping         jsonb not null default '{}',
  return_days      int  not null default 14,
  faq              jsonb not null default '[]',
  active           boolean not null default true,
  created_at       timestamptz not null default now()
);

create table if not exists products (
  id               text primary key default gen_random_uuid()::text,
  site_id          text not null references sites(id) on delete cascade,
  slug             text not null,
  title            text not null,
  subtitle         text not null default '',
  description      text not null default '',
  highlights       jsonb not null default '[]',
  specs            jsonb not null default '[]',
  faq              jsonb not null default '[]',
  category         text not null default '',
  price_cents      int  not null check (price_cents >= 0),
  compare_at_cents int,
  cost_cents       int,
  stock            int,              -- null = stock non suivi (dropshipping)
  images           jsonb not null default '[]',
  sku              text not null default '',
  gtin             text not null default '',
  brand            text not null default '',
  supplier         text not null default '',
  supplier_url     text not null default '',
  seo_title        text not null default '',
  seo_description  text not null default '',
  active           boolean not null default true,
  position         int  not null default 0,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  unique (site_id, slug)
);

create table if not exists guides (
  id               text primary key default gen_random_uuid()::text,
  site_id          text not null references sites(id) on delete cascade,
  slug             text not null,
  title            text not null,
  excerpt          text not null default '',
  body             text not null default '',
  product_ids      jsonb not null default '[]',
  seo_title        text not null default '',
  seo_description  text not null default '',
  published        boolean not null default false,
  published_at     timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  unique (site_id, slug)
);

create table if not exists orders (
  id                    text primary key default gen_random_uuid()::text,
  number                bigint generated by default as identity (start with 1001) unique,
  site_id               text not null references sites(id),
  stripe_session_id     text unique,
  stripe_payment_intent text,
  email                 text not null default '',
  name                  text not null default '',
  phone                 text not null default '',
  shipping_address      jsonb,
  items                 jsonb not null default '[]',
  subtotal_cents        int not null default 0,
  shipping_cents        int not null default 0,
  total_cents           int not null default 0,
  currency              text not null default 'eur',
  status                text not null default 'paid'
                        check (status in ('paid','sent_to_supplier','shipped','delivered','refunded','cancelled')),
  tracking_number       text not null default '',
  tracking_url          text not null default '',
  notes                 text not null default '',
  mode                  text not null default 'live' check (mode in ('live','test','demo')),
  created_at            timestamptz not null default now(),
  updated_at            timestamptz not null default now()
);

create index if not exists orders_site_created on orders (site_id, created_at desc);
create index if not exists orders_status on orders (status);
create index if not exists orders_email on orders (lower(email));
create index if not exists products_site on products (site_id, position);

-- Mise à jour du stock sans risque de doublon si deux commandes arrivent en même temps.
create or replace function adjust_stock(p_id text, p_delta int)
returns void language sql as $$
  update products set stock = greatest(0, stock + p_delta), updated_at = now()
  where id = p_id and stock is not null;
$$;

-- Sécurité : personne ne peut lire ou écrire ces tables depuis un navigateur.
-- Le site y accède uniquement côté serveur avec la clé "service_role", qui contourne ces règles.
alter table sites    enable row level security;
alter table products enable row level security;
alter table guides   enable row level security;
alter table orders   enable row level security;
